# Edge node firmware: near-miss fall detection on a TinyS3 (ESP32-S3).
#
# The IMU (WitMotion WT9011DCL-BT50) is read over BLE; every STEP_MS the last
# WINDOW_MS of data are classified on the device and each detected near-miss
# event is published as one MQTT message on the local (edge-level) broker,
# from which the fog node forwards it. Raw IMU data never leave the device.
#
# Configuration:
#   config.json      network, MQTT, IMU address, acquisition and window settings
#   battery_test.py  MODE = None for normal operation, or a battery test mode
#   lib/model_device.py, lib/model_device.bin, lib/model_input_array.py
#                    the model, generated by the training pipeline

import gc
import json
import sys
import bluetooth
import uasyncio as asyncio

import battery_test as bt
from lib.console import log
from lib.peripherals.led import TinyS3Led
from lib.primitives.queue import Queue
from coroutines.bluetooth_handler import find_sensor
from coroutines.data_processor import acquire_3p5hz, acquire_100hz
from coroutines.preprocessor import Preprocessor, buffer_capacity

print("Firmware starting...")

_CFG_FILENAME = "config.json"
_RECONNECT_DELAY_S = 2


def load_config():
    try:
        with open(_CFG_FILENAME) as f:
            cfg = json.load(f)
    except Exception as e:
        print("main: error while reading config file:", e)
        sys.exit()
    mode = cfg.get("ACQUISITION_MODE", "3.5Hz")
    if mode not in ("3.5Hz", "100Hz"):
        print('main: ACQUISITION_MODE must be "3.5Hz" or "100Hz"')
        sys.exit()
    cfg["ACQUISITION_MODE"] = mode      # the default is used if the key is missing
    window_ms = int(cfg.get("WINDOW_MS", 2000))
    step_ms = int(cfg.get("STEP_MS", 1000))
    if not 0 < step_ms <= window_ms:
        print("main: STEP_MS must be > 0 and <= WINDOW_MS")
        sys.exit()
    if bt.WIFI and cfg.get("wifi_ssid", "").startswith("YOUR_"):
        print("main: fill in wifi_ssid and wifi_pass in config.json")
    return cfg


def setup_network(cfg):
    """Wi-Fi and clock synchronisation only when MQTT is used; otherwise the
    radio is switched off."""
    from lib.wifi_manager import WiFiManager, radio_off
    if not bt.WIFI:
        radio_off()
        log("main: Wi-Fi off")
        return
    wm = WiFiManager(cfg["wifi_ssid"], cfg["wifi_pass"])
    # if the Wi-Fi is not available now, the MQTT task connects later and then
    # synchronises the clock; queued messages get their clock times only when
    # published, so events detected before the synchronisation are dated
    # correctly (if NTP is never reached, times count from 2000-01-01 at boot)
    cfg["_rtc_synced"] = wm.do_connect() and wm.sync_RTC(cfg.get("ntp_host"))


async def imu_session(cfg, led, on_sample, state):
    """Find the IMU, connect and acquire until the connection is lost."""
    service_uuid = bluetooth.UUID(cfg["IMU_SERVICE"])
    led.blue()
    device = await find_sensor(cfg["IMU_MAC_ADDRESS"], service_uuid)
    log("main: IMU found")
    connection = await device.device.connect()
    async with connection:
        service = await connection.service(service_uuid)
        char_read = await service.characteristic(bluetooth.UUID(cfg["IMU_CHAR_READ"]))
        char_write = await service.characteristic(bluetooth.UUID(cfg["IMU_CHAR_WRITE"]))
        if cfg.get("register_data_mode"):
            led.orange()
        else:
            led.green()
        state["connected"] = True
        bt.on_imu_connected()
        # three purple blinks: the IMU has been found (also during battery tests)
        asyncio.create_task(led.blink("purple", 3))
        if cfg["ACQUISITION_MODE"] == "100Hz":
            await acquire_100hz(char_read, char_write, on_sample, cfg)
        else:
            await char_read.subscribe(notify=True)
            await acquire_3p5hz(char_read, char_write, on_sample,
                                int(cfg.get("SAMPLE_PERIOD_MS", 284)))


async def imu_task(cfg, led, on_sample):
    """Keep the IMU connected: after a disconnection, search and reconnect.

    In battery test modes A, B, C, W, W1 the IMU may be used only while a test is running
    (battery_test.imu_allowed): before the test the task waits, and when the
    test ends the connection is closed so that another board can use the IMU.
    """
    waiting_shown = False
    while True:
        if not bt.imu_allowed():
            if not waiting_shown:
                log("main: IMU not connected until the battery test starts")
                waiting_shown = True
            await asyncio.sleep(1)
            continue
        waiting_shown = False
        state = {"connected": False}
        session = asyncio.create_task(imu_session(cfg, led, on_sample, state))
        released = False
        try:
            while not session.done():
                if not bt.imu_allowed():
                    session.cancel()            # leaves the connection context: disconnects
                    released = True
                    break
                await asyncio.sleep(1)
            await session
        except asyncio.CancelledError:
            if not released:
                raise                           # this task itself was cancelled
            log("main: battery test over, IMU released")
        except Exception as e:      # disconnection, timeout, BLE error
            log("main: IMU connection lost:", repr(e))
        led.red()
        if state["connected"]:
            bt.on_imu_disconnected()
        await asyncio.sleep(_RECONNECT_DELAY_S)


async def main(cfg):
    led = TinyS3Led(enabled=bt.LED_ON)
    led.blue()
    tasks = []
    sinks = []          # callbacks that receive every decoded sample
    sensor_id = cfg["mqtt_client_id"]
    outgoing = Queue(maxsize=10)        # outgoing event messages (up to ten)

    if cfg.get("register_data_mode"):
        # data recording: samples are saved to flash, nothing else runs
        from coroutines.save_data import DataRecorder, get_unique_filename
        name = get_unique_filename()
        print("main: recording data to", name)
        sinks.append(DataRecorder(name).add)
    else:
        if bt.INFERENCE or bt.WIFI:
            from coroutines.machine_learning_inference import configure_time
            configure_time(cfg)
        if bt.PREPROCESS:
            import lib.model_input_array as features
            capacity = buffer_capacity(float(cfg.get("SAMPLING_RATE_HZ", 3.5)),
                                       int(cfg.get("WINDOW_MS", 2000)))
            pre = Preprocessor(features.REQUIRED_DIMENSIONS, capacity)
            sinks.append(pre.add)
        if bt.INFERENCE:
            from coroutines.machine_learning_inference import load_model, inference_task
            load_model()
            tasks.append(inference_task(pre.buffer, outgoing, sensor_id, cfg))
        if bt.WIFI:
            from coroutines.mqtt import Publisher, mqtt_task, simulated_event_task
            publisher = Publisher(cfg)
            tasks.append(mqtt_task(outgoing, publisher))
            from coroutines.machine_learning_inference import event_message, window_message, payload
            import time
            now = time.ticks_ms()
            bt.set_info("event_msg_bytes", len(payload(event_message(
                {"start": now, "end": now, "windows": 2}, sensor_id))))
            bt.set_info("window_msg_bytes", len(payload(window_message(
                now, 2000, sensor_id, "near_miss_window_simulated"))))
            if bt.SIMULATED_EVENTS:
                tasks.append(simulated_event_task(outgoing, sensor_id, cfg))

    def on_sample(t_ms, sample):
        bt.on_imu_packet()
        for sink in sinks:
            sink(t_ms, sample)

    tasks.append(imu_task(cfg, led, on_sample))
    # battery tests: one short green blink at every log line, to show that the
    # test is running (the LED is otherwise off)
    tasks.append(bt.supervisor_task(
        heartbeat=lambda: asyncio.create_task(led.blink("green", 1, on_ms=100, off_ms=0))))
    gc.collect()
    log("main: free memory %d bytes" % gc.mem_free())
    await asyncio.gather(*[asyncio.create_task(t) for t in tasks])


if __name__ == "__main__":
    gc.enable()
    config = load_config()
    if bt.ACTIVE:
        # battery tests: a distinct MQTT client id per board, so that a board
        # charging with Wi-Fi on never disconnects the board under test
        config["mqtt_client_id"] += "_" + bt.device_id()[-6:]
        # acquisition settings in the log header (3.5 Hz and 100 Hz tests are analysed apart)
        bt.set_info("acquisition_mode", config["ACQUISITION_MODE"])
        bt.set_info("sampling_rate_hz", config.get("SAMPLING_RATE_HZ"))
        bt.set_info("sample_period_ms", config.get("SAMPLE_PERIOD_MS", 284))
    log("main: acquisition mode", config["ACQUISITION_MODE"], "| battery test mode", bt.MODE)
    setup_network(config)
    if bt.ACTIVE and bt.WIFI:
        bt.set_info("clock_synced_at_start", int(bool(config["_rtc_synced"])))
    try:
        asyncio.run(main(config))
    except KeyboardInterrupt:
        print("Interrupted")
    finally:
        asyncio.new_event_loop()    # clear retained state
